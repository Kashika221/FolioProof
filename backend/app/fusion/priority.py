"""Source precedence.

When two sources disagree about the same fact, the more authoritative one wins.
The ordering is deliberate:

    resume       -- the candidate curates this per application; it is the most
                    deliberate and most recently checked statement of fact.
    linkedin     -- maintained, but often stale and edited less carefully.
    github       -- generated by tooling. Repo names and language stats are
                    facts about code, not claims the candidate wrote about
                    themselves.
    cover_letter -- narrative and tone, not a record of dates or titles.

Note the deliberate exception in `prefer_attribute`: GitHub stays authoritative
for facts only GitHub can know (stars, forks, repo URL, language breakdown).
A résumé cannot out-rank GitHub on a repository's star count.
"""
from __future__ import annotations

from typing import Iterable, Sequence, TypeVar

from app.models.claims import Claim, Evidence, SourceId

# Lower number == higher authority.
SOURCE_PRIORITY: dict[str, int] = {
    "resume": 0,
    "linkedin": 1,
    "github": 2,
    "cover_letter": 3,
}

DEFAULT_PRIORITY = 99

# Fields GitHub owns regardless of precedence, because no other source can
# legitimately supply them.
GITHUB_AUTHORITATIVE_FIELDS = frozenset({
    "repo", "url", "homepage", "stars", "forks", "topics",
    "languages", "primary_language", "pushed_at", "readme",
})

def rank(source: str | None) -> int:
    return SOURCE_PRIORITY.get(source or "", DEFAULT_PRIORITY)

def best_source(sources: Iterable[str]) -> str | None:
    """The most authoritative source in the set."""
    ordered = sorted(sources, key = rank)
    return ordered[0] if ordered else None

def primary_evidence(evidence: Sequence[Evidence]) -> Evidence | None:
    """The evidence item from the most authoritative source."""
    if not evidence:
        return None
    return min(evidence, key = lambda e: rank(e.source_id))

def sort_evidence(evidence: Sequence[Evidence]) -> list[Evidence]:
    """Evidence ordered most-authoritative first (stable within a source)."""
    return sorted(evidence, key = lambda e: rank(e.source_id))

T = TypeVar("T")

def prefer_attribute(
    key: str,
    candidates: dict[str, T],
) -> T | None:
    """Pick an attribute value from {source: value} using precedence.

    GitHub-owned keys short-circuit to GitHub's value when it has one.
    """
    usable = {s: v for s, v in candidates.items() if v not in (None, "", [], {})}
    if not usable:
        return None

    if key in GITHUB_AUTHORITATIVE_FIELDS and "github" in usable:
        return usable["github"]

    winner = best_source(usable.keys())
    return usable[winner] if winner else None

def merge_by_priority(claims: Sequence[Claim]) -> Claim:
    """Fold duplicate claims into one, letting the highest-priority source win.

    The surviving claim keeps evidence from *every* source (that is what makes
    corroboration visible), but its `value` and conflicting attributes come from
    the most authoritative contributor.
    """
    if not claims:
        raise ValueError("cannot merge an empty claim list")

    ordered = sorted(
        claims, key=lambda c: rank(best_source(c.sources) or "")
    )
    winner = ordered[0]

    evidence: list[Evidence] = []
    seen: set[tuple[str, str]] = set()
    for claim in ordered:
        for e in claim.evidence:
            key = (e.source_id, e.raw_text)
            if key not in seen:
                seen.add(key)
                evidence.append(e)

    # Attributes: walk from least to most authoritative so the winner overwrites.
    attributes: dict = {}
    for claim in reversed(ordered):
        for k, v in claim.attributes.items():
            if v in (None, "", [], {}):
                continue
            if k in GITHUB_AUTHORITATIVE_FIELDS and "github" not in claim.sources:
                # Don't let a résumé overwrite a star count with a stale guess.
                attributes.setdefault(k, v)
            else:
                attributes[k] = v

    return winner.model_copy(update={
        "evidence": sort_evidence(evidence),
        "attributes": attributes,
        "confidence": max(c.confidence for c in ordered),
    })